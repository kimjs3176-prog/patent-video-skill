NOTE = {"C": 0, "D": 2, "E": 4, "F": 5, "G": 7, "A": 9, "B": 11}
QUAL = {"": [0, 4, 7], "maj": [0, 4, 7], "m": [0, 3, 7], "min": [0, 3, 7], "7": [0, 4, 7, 10], "maj7": [0, 4, 7, 11],
        "m7": [0, 3, 7, 10], "m9": [0, 3, 7, 10, 14], "maj9": [0, 4, 7, 11, 14], "9": [0, 4, 7, 10, 14], "6": [0, 4, 7, 9],
        "m6": [0, 3, 7, 9], "sus2": [0, 2, 7], "sus4": [0, 5, 7], "add9": [0, 4, 7, 14], "madd9": [0, 3, 7, 14],
        "dim": [0, 3, 6], "aug": [0, 4, 8], "7sus4": [0, 5, 7, 10]}


def pc(name):
    m = re.match(r"([A-G])([#b]?)", name)
    if not m:
        raise ValueError(f"bad note {name!r}")
    return (NOTE[m.group(1)] + {"#": 1, "b": -1, "": 0}[m.group(2)]) % 12


def chord(sym):
    """'A/C#' → (root pc, intervals, bass pc)."""
    main, _, bass = sym.partition("/")
    m = re.match(r"([A-G][#b]?)(.*)$", main.strip())
    if not m or m.group(2) not in QUAL:
        raise ValueError(f"unsupported chord {sym!r} (qualities: {', '.join(k or 'major' for k in QUAL)})")
    r = pc(m.group(1))
    return r, QUAL[m.group(2)], pc(bass) if bass else r


def transpose(prog, key, ref):
    """Shift a preset progression from its reference key to `key` (semitones on the circle, nearest direction)."""
    if not key:
        return prog
    d = (pc(key) - pc(ref)) % 12
    names = ["C", "C#", "D", "Eb", "E", "F", "F#", "G", "Ab", "A", "Bb", "B"]
    def mv(s):
        return re.sub(r"[A-G][#b]?", lambda m: names[(pc(m.group(0)) + d) % 12], s)
    return [mv(s) for s in prog]


def hz(midi):
    return 440.0 * 2 ** ((midi - 69) / 12)


# ---------------------------------------------------------------- instruments (mono note, numpy)
def _t(dur):
    return np.arange(int(dur * SR)) / SR


def _adsr(n, a, d, s, r, hold):
    t = np.arange(n) / SR
    env = np.where(t < a, t / max(a, 1e-4), s + (1 - s) * np.exp(-(t - a) / max(d, 1e-4)))
    rel = t > hold
    env[rel] *= np.exp(-(t[rel] - hold) / max(r, 1e-4))
    return env


def epiano(f, dur, vel):
    t = _t(dur + 1.6)
    idx = 2.2 * np.exp(-t * 4.0) + 0.35
    body = np.sin(2 * np.pi * f * t + idx * np.sin(2 * np.pi * f * t))
    tine = 0.18 * np.exp(-t * 14) * np.sin(2 * np.pi * f * 14 * t)
    env = np.exp(-t * (0.9 + f / 900)) * np.minimum(1, t / 0.004)
    env[t > dur] *= np.exp(-(t[t > dur] - dur) * 5)
    return (body + tine) * env * vel


def piano(f, dur, vel):
    t = _t(dur + 2.0)
    y = np.zeros_like(t)
    B = 0.0004
    for k in range(1, 9):
        fk = k * f * math.sqrt(1 + B * k * k)
        if fk > 12000:
            break
        y += (1 / k ** 1.4) * np.exp(-t * (0.6 + 0.35 * k + f / 1500)) * np.sin(2 * np.pi * fk * t + k)
    y *= np.minimum(1, t / 0.003)
    y[t > dur] *= np.exp(-(t[t > dur] - dur) * 6)
    rng = np.random.default_rng(int(f))
    y[:300] += rng.normal(0, 0.04, min(300, len(y))) * np.linspace(1, 0, min(300, len(y)))
    return y * vel


def marimba(f, dur, vel):
    t = _t(min(dur, 0.9) + 0.6)
    y = (np.exp(-t * 3.2) * np.sin(2 * np.pi * f * t) + 0.32 * np.exp(-t * 11) * np.sin(2 * np.pi * f * 3.93 * t)
         + 0.1 * np.exp(-t * 22) * np.sin(2 * np.pi * f * 9.2 * t))
    return y * np.minimum(1, t / 0.002) * vel


def guitar(f, dur, vel):
    t = _t(dur + 1.2)
    y = np.zeros_like(t)
    for k in range(1, 11):
        if k * f > 10000:
            break
        y += (1 / k) * (0.6 + 0.4 * math.sin(k * 1.3)) * np.exp(-t * (1.1 + 0.7 * k)) * np.sin(2 * np.pi * k * f * t)
    y *= np.minimum(1, t / 0.002)
    y[t > dur] *= np.exp(-(t[t > dur] - dur) * 4)
    return y * vel


def celesta(f, dur, vel):
    t = _t(dur + 1.8)
    idx = 1.6 * np.exp(-t * 6)
    y = np.sin(2 * np.pi * f * t + idx * np.sin(2 * np.pi * f * 3.5 * t)) + 0.25 * np.exp(-t * 3) * np.sin(2 * np.pi * f * 2.76 * t)
    return y * np.exp(-t * 1.6) * np.minimum(1, t / 0.002) * vel


def pad(f, dur, vel, strings=False):
    n = int((dur + 3.0) * SR)
    t = np.arange(n) / SR
    y = np.zeros(n)
    vib = (0.004 * np.sin(2 * np.pi * 5.2 * t) * np.minimum(1, t / 1.2)) if strings else 0
    for det in (-0.006, 0.0, 0.0065):
        ph = 2 * np.pi * f * (1 + det) * (t + (np.cumsum(vib) / SR if strings else 0))
        for k in range(1, 10):
            if k * f > 7000:
                break
            y += (1 / k) * (0.92 ** (k * k)) * np.sin(k * ph + det * 100 * k)
    env = _adsr(n, 0.4 if strings else 0.25, 1.2, 0.75, 0.6, dur)
    return y * env * vel / 3


def bass(f, dur, vel):
    n = int((dur + 0.6) * SR)
    t = np.arange(n) / SR
    y = np.sin(2 * np.pi * f * t) + 0.28 * np.sin(4 * np.pi * f * t) + 0.08 * np.sin(6 * np.pi * f * t)
    y = np.tanh(1.4 * y) * _adsr(n, 0.006, 0.35, 0.55, 0.12, dur)
    return y * vel


def kick(vel):
    t = _t(0.45)
    f = 45 + 75 * np.exp(-t * 28)
    return np.sin(2 * np.pi * np.cumsum(f) / SR) * np.exp(-t * 9) * vel


def shaker(vel, rng):
    n = int(0.07 * SR)
    x = np.diff(rng.normal(0, 1, n + 3))
    x = (x[:-2] + 2 * x[1:-1] + x[2:]) / 4  # soften the top: a shaker, not white hiss
    x /= np.sqrt(np.mean(x ** 2)) + 1e-9
    t = np.arange(n) / SR
    return x * np.minimum(1, t / 0.004) * np.exp(-t * 55) * vel * 0.22


def clap(vel, rng):
    """Three quick noise bursts and a short tail: the backbeat on 2 and 4."""
    n = int(0.18 * SR)
    x = np.diff(rng.normal(0, 1, n + 1))
    x = x - np.convolve(x, np.ones(9) / 9, "same")  # keep the crack, lose the low thud
    x = (x + np.roll(x, 1)) / 2  # and the harshest fizz
    x /= np.sqrt(np.mean(x ** 2)) + 1e-9
    t = np.arange(n) / SR
    env = sum(np.where(t >= o, np.exp(-(t - o) * 90), 0) for o in (0, 0.009, 0.018)) + 0.35 * np.exp(-t * 22)
    return x * env * np.minimum(1, t / 0.001) * vel * 0.05


def rim(vel, rng):
    t = _t(0.08)
    return (0.6 * np.sin(2 * np.pi * 1750 * t) + 0.25 * np.diff(rng.normal(0, 1, len(t) + 1))) * np.minimum(1, t / 0.002) * np.exp(-t * 60) * vel


VOICE = {"epiano": epiano, "piano": piano, "marimba": marimba, "guitar": guitar, "celesta": celesta}


# ---------------------------------------------------------------- arrangement
class Bus:
    def __init__(self, n):
        self.dry = np.zeros((2, n))
        self.wet = np.zeros((2, n))

    def add(self, sig, at, gain=1.0, pan=0.0, send=0.25):
        i = int(at * SR)
        if i >= self.dry.shape[1] or len(sig) == 0:
            return
        sig = sig[: self.dry.shape[1] - i].copy()
        k = min(len(sig), int(0.012 * SR))  # every note ends on a short fade: no click where its buffer stops
        sig[len(sig) - k:] *= np.cos(np.linspace(0, np.pi / 2, k)) ** 2
        k = min(len(sig), 64)
        sig[:k] *= np.linspace(0, 1, k)  # and starts without a step
        l, r = math.cos((pan + 1) * math.pi / 4), math.sin((pan + 1) * math.pi / 4)
        for ch, g in ((0, l), (1, r)):
            self.dry[ch, i:i + len(sig)] += sig * gain * g
            self.wet[ch, i:i + len(sig)] += sig * gain * g * send


def voicing(root, ivs, prev, lo=55, hi=74):
    """Chord tones in [lo, hi] closest to the previous voicing (smooth voice leading)."""
    cands = []
    for inv in range(len(ivs)):
        base = [root + iv for iv in ivs]
        notes = sorted(((n - lo) % 12) + lo for n in base[inv:] + [x + 12 for x in base[:inv]])
        notes = [n if n <= hi else n - 12 for n in notes]
        cands.append(sorted(set(notes)))
    if not prev:
        return cands[0]
    return min(cands, key=lambda v: sum(min(abs(a - b) for b in prev) for a in v))


def _fft_filter(x, lo=None, hi=None, pocket=0.0):
    """High/low pass, and `pocket` dB cut around the speech presence band (1–4 kHz) so a narrator sits on top."""
    X = np.fft.rfft(x, axis=-1)
    f = np.fft.rfftfreq(x.shape[-1], 1 / SR)
    g = np.ones_like(f)
    if pocket:
        oct_ = np.log2(np.maximum(f, 1) / 2000.0)
        g *= 10 ** (-pocket * np.exp(-(oct_ / 0.9) ** 2) / 20)
    if lo:
        g *= 1 / np.sqrt(1 + (lo / np.maximum(f, 1)) ** 4)
    if hi:
        g *= 1 / np.sqrt(1 + (f / hi) ** 4)
    return np.fft.irfft(X * g, n=x.shape[-1], axis=-1)


def reverb(wet, rt=2.6, seed=0):
    rng = np.random.default_rng(seed)
    n = int(rt * SR)
    t = np.arange(n) / SR
    out = np.zeros_like(wet)
    m = wet.shape[1] + n
    size = 1 << (m - 1).bit_length()
    for ch in range(2):
        ir = rng.normal(0, 1, n) * np.exp(-t * 6.9 / rt)
        ir[: int(0.012 * SR)] = 0  # pre-delay
        ir = _fft_filter(ir[None, :], lo=200, hi=6500)[0]
        ir /= np.sqrt(np.sum(ir ** 2)) + 1e-9
        y = np.fft.irfft(np.fft.rfft(wet[ch], size) * np.fft.rfft(ir, size), size)[: wet.shape[1]]
        out[ch] = y
    return out


def spec_of(spec):
    s = dict(PRESETS.get((spec or {}).get("mood") or "bright-tech", PRESETS["bright-tech"]))
    ref = re.match(r"[A-G][#b]?", s["progression"][0]).group(0)
    s.update({k: v for k, v in (spec or {}).items() if v not in (None, "")})
    if spec and spec.get("key") and not spec.get("progression"):
        s["progression"] = transpose(s["progression"], spec["key"], ref)
    s["bpm"] = float(min(160, max(70, s["bpm"])))
    s.setdefault("chord_bars", 1)
    return s


def render(spec=None):
    s = spec_of(spec)
    rng = np.random.default_rng(int(s.get("seed", 1)))
    beat = 60 / s["bpm"]
    bar = 4 * beat
    nbars = int(math.ceil(LENGTH / bar))
    n = int((nbars * bar + 3) * SR)
    bus = Bus(n)
    chords = [chord(c) for c in s["progression"]]
    cb = max(1, int(s["chord_bars"]))
    intro, outro = 2, 2  # short intro: the groove arrives within a few seconds
    lift = nbars - outro - max(4, nbars // 3)
    prev = None
    arp_pat = [0, 1, 2, 3, 2, 1, 3, 4] if rng.random() < 0.5 else [0, 2, 1, 3, 2, 4, 3, 1]
    keys_pat = [(0, 1.0), (1.5, 0.75), (2, 0.6), (3.5, 0.8)] if rng.random() < 0.6 else [(0.5, 0.8), (1.5, 0.75), (2.5, 0.8), (3.5, 0.7)]
    # bouncy bass: root on the beat, the octave on the off-beats
    bass_pat = [(0, 1.0, 0.7, 0), (1.5, 0.6, 0.35, 12), (2, 0.9, 0.7, 0), (3.5, 0.6, 0.35, 12)]
    keys = VOICE.get(s.get("keys"))
    arp = VOICE.get(s.get("arp"))
    lead = VOICE.get(s.get("lead"))
    padf = (lambda f, d, v: pad(f, d, v, strings=True)) if s.get("pad") == "strings" else (pad if s.get("pad") != "none" else None)
    # a short, singable hook: rhythm and contour fixed per piece (repetition is what makes it catchy)
    hook_rhythm = [0, 0.5, 1, 2, 2.5, 3] if rng.random() < 0.5 else [0, 1, 1.5, 2.5, 3]
    hook_shape = [int(x) for x in rng.integers(0, 4, len(hook_rhythm))]

    def hum(t):
        return max(0.0, t + rng.normal(0, 0.005))

    for b in range(nbars):
        t0 = b * bar
        root, ivs, bp = chords[(b // cb) % len(chords)]
        v = voicing(root, ivs, prev, lo=57, hi=76)
        prev = v
        main = intro <= b < nbars - outro
        last = b >= nbars - outro
        density = 0.6 if b < intro else (1.0 if b >= lift and not last else 0.88)
        if padf and b % cb == 0:  # a soft bed under the rhythm, not a swell
            for m in v:
                bus.add(padf(hz(m), bar * cb + 0.1, 0.1 * density), t0, pan=rng.uniform(-0.5, 0.5), send=0.3)
        if keys:  # short off-beat stabs: the cheerful push of the groove
            for off, vel in (keys_pat if not last else [(0, 0.9)]):
                d = beat * (0.55 if not last else 3)
                for j, m in enumerate(v):
                    bus.add(keys(hz(m), d, 0.18 * vel * density * rng.uniform(0.85, 1.0)), hum(t0 + off * beat + j * 0.006),
                            pan=-0.25 + 0.15 * j, send=0.18)
        if arp and not last:
            pool = sorted(set([x for m in v for x in (m, m + 12, m + 24) if 64 <= x <= 84]))
            if pool:
                for k in range(8):
                    if rng.random() > 0.94:
                        continue
                    m = pool[arp_pat[k % 8] % len(pool)]
                    bus.add(arp(hz(m), bar / 8 * 0.8, 0.12 * density * rng.uniform(0.75, 1.0)), hum(t0 + k * bar / 8),
                            pan=0.35 if k % 2 else -0.35, send=0.22)
        if main or b == nbars - outro:  # bass enters with the groove and lands the last chord
            for off, vel, ln, octv in (bass_pat if main else [(0, 1.0, 3.0, 0)]):
                f = hz(36 + (bp - 36) % 12 + octv)
                bus.add(bass(f, beat * ln, 0.32 * vel), hum(t0 + off * beat), send=0.04)
        if s.get("perc") in ("light", "pulse") and main:
            if s["perc"] == "pulse":
                for k, kv in ((0, 0.6), (2, 0.5), (3.5, 0.25)):
                    bus.add(kick(kv), t0 + k * beat, send=0.02)
            for k in (1, 3):  # backbeat claps from the first groove bar
                bus.add(clap(0.9 if s["perc"] == "pulse" else 0.6, rng), hum(t0 + k * beat), pan=-0.1, send=0.25)
            for k in range(16 if s["perc"] == "pulse" else 8):
                step = bar / (16 if s["perc"] == "pulse" else 8)
                acc = 0.16 if k % 2 else 0.08
                bus.add(shaker(acc * density, rng), hum(t0 + k * step), pan=0.4, send=0.1)
        if lead and main and (b >= lift or b % 4 in (0, 1)):  # the hook, high and light, coming back every few bars
            tones = sorted(set(m + 12 * o for m in v for o in (1, 2) if 74 <= m + 12 * o <= 91)) or [v[-1] + 12]
            for off, sh in zip(hook_rhythm, hook_shape):
                m = tones[min(sh, len(tones) - 1)]
                bus.add(lead(hz(m), beat * 0.7, 0.085 * (1.0 if b >= lift else 0.75)), hum(t0 + off * beat), pan=0.15, send=0.3)
    mix = bus.dry + reverb(bus.wet, 1.5, int(s.get("seed", 1)))  # a short, bright room (a long hall sounds solemn)
    mix = _fft_filter(mix, lo=32, hi=15000, pocket=6.0)  # leave the voice its room
    mix = np.tanh(mix / (np.max(np.abs(mix)) + 1e-9) * 1.25)  # glue: a soft clip into the master
    return mix / (np.max(np.abs(mix)) + 1e-9) * 0.9, s


def write_wav(mix, path):
    data = (np.clip(mix.T, -1, 1) * 32767).astype("<i2")
    with wave.open(path, "wb") as w:
        w.setnchannels(2)
        w.setsampwidth(2)
        w.setframerate(SR)
        w.writeframes(data.tobytes())


def bed(spec, dst):
    """Compose, perform and master one bed as dst (mp3, 60.5 s with fades). Returns the resolved spec."""
    sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
    import music
    mix, s = render(spec)
    with tempfile.TemporaryDirectory(prefix="compose-") as d:
        wav = os.path.join(d, "bed.wav")
        write_wav(mix, wav)
        music.to_bed(wav, dst)
    return s


def track_name(c):
    """data/music file for a content's own `music` block (the hash keeps an edited block from reusing an old file)."""
    sp = c.get("music")
    if not isinstance(sp, dict):
        return None
    h = hashlib.sha1(json.dumps(spec_of(sp), sort_keys=True).encode("utf-8")).hexdigest()[:8]
    return f'{c["appno"]}-{h}.mp3'


def ensure_track(c):
    """Make the patent's own bed in data/music if its content has a `music` block. Returns the file name or None."""
    name = track_name(c)
    if not name:
        return None
    d = os.path.join(ROOT, "data", "music")
    os.makedirs(d, exist_ok=True)
    if not os.path.exists(os.path.join(d, name)):
        bed(c["music"], os.path.join(d, name))
    return name


