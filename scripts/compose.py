"""Background music composed by the pipeline itself: no key, no service, no third-party rights.

Claude (the agent running the skill) writes the composition as data, a `music` block, and this module performs it with
numpy: FM electric piano, additive piano, marimba, nylon guitar, celesta, detuned pads and strings, a round bass and a
soft kit, then a stereo convolution reverb and a gentle master. ffmpeg (music.to_bed) trims, fades, loudness-normalises
and writes the mp3.

  {"mood": "bright-tech",                 # preset to start from: bright-tech | green-field | clean-lab | warm-craft
   "bpm": 124, "key": "D",                # optional overrides; key only transposes the preset's progression
   "progression": ["D", "A", "Bm", "G"],   # one chord per bar (or per chord_bars), looped
   "chord_bars": 1,
   "keys": "epiano", "arp": "marimba",    # epiano | piano | marimba | guitar | celesta | none
   "pad": "pad", "lead": "celesta",       # pad | strings | none ; the sparse top line (kept above the voice range)
   "perc": "light", "seed": 7}            # none | light | pulse

Where it is used:
- music.py --mode compose (and produce.py when assets/music is empty and no GEMINI_API_KEY): four preset beds
  m01..m04 in assets/music that the videos rotate through.
- a content JSON's own `music` block: that patent gets its own bed, data/music/<appno>-<hash>.mp3 (made by produce.py
  before the build; postprocess copies it into the video project).

Usage: python -I tools/compose.py <out.mp3> [mood | spec.json]     (one bed, for listening)
"""
