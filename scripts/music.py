LYRIA_URL = "https://generativelanguage.googleapis.com/v1beta/interactions"
LYRIA_REVISION = "2026-05-20"
LYRIA_MODELS = [m for m in (os.environ.get("LYRIA_MODEL"), "lyria-3.5", "lyria-3-clip-preview") if m]  # full song first, 30 s clip as fallback


def env_key(*names):
    """The first of names set in the environment or the project's .env (NAME=value)."""
    for n in names:
        if os.environ.get(n):
            return os.environ[n].strip()
    env = os.path.join(ROOT, ".env")
    if os.path.exists(env):
        with open(env, encoding="utf-8-sig") as f:
            lines = f.read().splitlines()
        for n in names:
            for line in lines:
                if line.strip().startswith(n + "="):
                    v = line.split("=", 1)[1].strip().strip('"\'')
                    if v:
                        return v
    return None


def gemini_key():
    return env_key("GEMINI_API_KEY", "GOOGLE_API_KEY")


class KeyRejected(RuntimeError):
    """The API refused the key itself (invalid, expired, blocked for this API, project disabled): every model and every
    track would get the same answer, so Lyria stops at the first one."""


class Unavailable(RuntimeError):
    """No model can serve: each kept answering 429/5xx or could not be reached through the whole retry ladder (~85 s a
    model), or is not open to the key (403/404). The next track would only get, and wait for, the same."""


def api_error(e):
    """(the API's own message, whether it rejects the key itself) for an HTTPError. Google sends
    [{"error": {"message", "status", "details": [{"reason": "API_KEY_INVALID"}, ...]}}]: printed raw, ten lines a track."""
    try:
        raw = e.read(65536).decode("utf-8", "replace")
    except Exception:
        raw = ""
    try:
        d = json.loads(raw)
        err = (d[0] if isinstance(d, list) and d else d).get("error") or {}
    except (ValueError, AttributeError):
        err = {}
    err = err if isinstance(err, dict) else {"message": str(err)}
    msg = " ".join(str(err.get("message") or raw or e.reason).split())[:300]
    reasons = {str(x.get("reason") or "") for x in err.get("details") or [] if isinstance(x, dict)}
    # 400/403 also mean "this model is not open to the key" (then the next model may answer): only these are the key
    key = (e.code == 401 or err.get("status") == "UNAUTHENTICATED" or any(r.startswith("API_KEY") for r in reasons)
           or bool(reasons & {"SERVICE_DISABLED", "BILLING_DISABLED", "CONSUMER_SUSPENDED"}) or "api key not valid" in msg.lower())
    return msg, key


def lyria(prompt, dst_stem, key):
    """Generate one track with Lyria through the Gemini API; return (path, model). Raises KeyRejected or Unavailable when
    the failure would repeat for every track, RuntimeError when it may be this prompt's (a 400, no audio)."""
    last, stuck = "no model answered", True
    for model in dict.fromkeys(LYRIA_MODELS):
        body = json.dumps({"model": model, "input": prompt, "response_format": {"type": "audio"}}).encode("utf-8")
        req = urllib.request.Request(LYRIA_URL, data=body, headers={"Content-Type": "application/json", "Api-Revision": LYRIA_REVISION,
                                                                  "x-goog-api-key": key})
        for wait in (0, 5, 20, 60):  # rate limits and brief outages
            time.sleep(wait)
            try:
                with urllib.request.urlopen(req, timeout=600) as r:
                    d = json.load(r)
            except urllib.error.HTTPError as e:
                msg, bad_key = api_error(e)
                last = f"{model}: HTTP {e.code} {msg}"
                if bad_key:
                    raise KeyRejected(last) from None
                if e.code in (429, 500, 502, 503, 504):
                    continue
                stuck = stuck and e.code in (403, 404)  # the model is not open to the key; a 400 may be about this prompt
                break  # 400/403/404: try the next model
            except OSError as e:
                last = f"{model}: {e}"
                continue
            stuck = False
            blocks = [b for st in d.get("steps", []) if st.get("type") == "model_output" for b in st.get("content", []) if b.get("type") == "audio"]
            if not blocks or not blocks[0].get("data"):
                last = f"{model}: no audio in the response"
                break
            mime = blocks[0].get("mime_type") or blocks[0].get("mimeType") or "audio/mpeg"
            path = dst_stem + (".wav" if "wav" in mime else ".mp3")
            with open(path, "wb") as f:
                f.write(base64.b64decode(blocks[0]["data"]))
            return path, model
    raise (Unavailable if stuck else RuntimeError)(last)


def ensure(count=4):
    """Called by produce.py: make the beds of the default set (m01..m<count>) that assets/music lacks, with Lyria when a
    Gemini key is set and composing whatever it does not deliver, otherwise composing. Never stops the batch."""
    try:
        have = [f for f in os.listdir(MUSIC) if f.lower().endswith(".mp3")] if os.path.isdir(MUSIC) else []
        todo = missing(count)
    except Exception as e:  # music is optional: never stop the batch for it
        print("music: cannot check assets/music -", e, flush=True)
        return
    if not todo:
        return
    what = ("assets/music is empty" if not have else
            f"assets/music lacks {len(todo)} of the {min(count, len(MOODS))} default beds ({', '.join(n for n, _ in todo)})")
    if gemini_key():
        print(f"music: {what} - generating {len(todo)} with Google Lyria (Gemini API, billed per track; "
              "skip with --no-music-gen)", flush=True)
        try:
            generate_lyria(len(todo), slots=todo)
        except Exception as e:
            print("music: generation failed -", e, flush=True)
        rest = [s for s in todo if not os.path.exists(os.path.join(MUSIC, s[0]))]
        if not rest:
            return
        print(f"music: Lyria made {len(todo) - len(rest)}/{len(todo)} - composing the rest (no key needed; to have Lyria "
              "make them later, delete those beds once the key works)", flush=True)
        todo = rest
    else:
        print(f"music: {what} - composing {len(todo)} original beds (no key needed; GEMINI_API_KEY in .env "
              "switches to Google Lyria; skip with --no-music-gen)", flush=True)
    try:
        compose_beds(len(todo), slots=todo)
    except Exception as e:
        print("music: composing failed -", e, flush=True)


def missing(count):
    """[(file name, mood index)] of the default set m01..m<count> still to make, after removing what interrupted runs
    left: stale .part files and beds of ours cut short (older versions encoded straight into the .mp3, and a Ctrl+C there
    leaves a playable file that stops dead mid-video). [] when the folder holds mp3s of the user's own: theirs to manage."""
    os.makedirs(MUSIC, exist_ok=True)
    clean_parts(MUSIC)
    listed = {s.get("file") for s in sources() if isinstance(s, dict)}
    mp3 = sorted(f for f in os.listdir(MUSIC) if f.lower().endswith(".mp3"))
    theirs = [f for f in mp3 if not OWN.match(f) and f not in listed]
    filled = set()
    for f in filter(OWN.match, mp3):
        p = os.path.join(MUSIC, f)
        if not complete(p):  # removed even next to the user's music: it would play in the rotation and stop dead
            print(f"music: {f} is cut short ({duration(p):.1f} s of {LENGTH} s, an interrupted write) - removed"
                  + ("" if theirs else ", it will be made again"), flush=True)
            try:
                os.remove(p)
            except OSError as e:  # open in a player on Windows: making it again replaces it, or fails and says so
                print("music: cannot remove it -", e, flush=True)
            continue
        filled.add(int(OWN.match(f).group(1)))
    if theirs:
        return []
    return [(f"m{i + 1:02d}-{MOODS[i][0]}.mp3", i) for i in range(min(count, len(MOODS))) if i + 1 not in filled]


def plan(count):
    """[(file name, mood index)] for count new beds numbered after the mp3s already there (--force: add more)."""
    start = len([f for f in os.listdir(MUSIC) if f.lower().endswith(".mp3")]) if os.path.isdir(MUSIC) else 0
    return [(f"m{start + i + 1:02d}-{slug}.mp3", i) for i, (slug, _q, _p) in enumerate(MOODS[:count])]  # zero-padded: the builders rotate in sorted order


def complete(path):
    """True when path is a whole bed (to_bed writes LENGTH s; a cut-short file still plays, so only its length tells)."""
    try:
        return duration(path) >= LENGTH - 1
    except (OSError, ValueError):  # no ffprobe to ask: keep the file rather than delete a good one
        return True


def clean_parts(folder):
    """Remove the temporary files of killed processes (a .part is never an mp3, so nothing would else ever look at it)."""
    for f in os.listdir(folder) if os.path.isdir(folder) else []:
        p = os.path.join(folder, f)
        try:
            if PART.search(f) and time.time() - os.path.getmtime(p) > PART_AGE:  # a fresh one is another renderer's live encode
                os.remove(p)
        except OSError:
            pass


def sources():
    """SOURCES.json as a list ([] when absent or unreadable)."""
    try:
        with open(os.path.join(MUSIC, "SOURCES.json"), encoding="utf-8") as f:
            d = json.load(f)
        return d if isinstance(d, list) else []
    except (OSError, ValueError):
        return []


def _record(entry):
    """Note one finished bed in SOURCES.json: replaces an older note for the same file, drops notes for files that are
    gone, and is written whole or not at all (re-read each time: another renderer may have added its own)."""
    path = os.path.join(MUSIC, "SOURCES.json")
    keep = [s for s in sources() if isinstance(s, dict) and s.get("file") != entry["file"]
            and os.path.exists(os.path.join(MUSIC, str(s.get("file"))))]
    tmp = f"{path}.{os.getpid()}.part"
    try:
        with open(tmp, "w", encoding="utf-8") as f:
            json.dump(keep + [entry], f, ensure_ascii=False, indent=2)
        os.replace(tmp, path)
    except OSError as e:  # only the notes: the bed itself is in place, and the next beds still get made
        print("music: SOURCES.json not updated -", e, flush=True)
    finally:
        if os.path.exists(tmp):
            os.remove(tmp)


def compose_beds(count, slots=None):
    """count original beds from compose.py's presets, no key or service involved; slots [(file name, mood index)] names
    them (ensure() fills gaps), by default count new ones numbered after the mp3s already there."""
    import compose
    os.makedirs(MUSIC, exist_ok=True)
    slots = slots or plan(count)
    made = 0
    for name, i in slots:
        mood = MOODS[i][0]  # compose.PRESETS has the same four moods
        t = time.time()
        try:
            spec = compose.bed({"mood": mood}, os.path.join(MUSIC, name))
        except Exception as e:
            print(name, "FAILED:", e, flush=True)
            continue
        made += 1
        _record({"file": name, "provider": "composed", "mode": "compose", "spec": spec, "seconds": LENGTH,
                 "licence": LICENCE["composed"], "made": time.strftime("%Y-%m-%d")})
        print(name, f"ok (composed, {time.time() - t:.0f}s)", flush=True)
    print(f"{made}/{len(slots)} tracks in assets/music", flush=True)
    return made


def generate_lyria(count, force=False, slots=None):
    """Lyria beds for slots (as compose_beds). Stops at the first failure that would repeat for every track (the key
    refused, Lyria unreachable) instead of trying each track and model again; returns how many were made."""
    key = gemini_key()
    os.makedirs(MUSIC, exist_ok=True)
    todo = slots or plan(count)
    made = 0
    for name, i in todo:
        slug, _query, prompt = MOODS[i]
        t = time.time()
        try:
            with tempfile.TemporaryDirectory(prefix="bgm-", ignore_cleanup_errors=True) as work:
                src, model = lyria(prompt, os.path.join(work, slug), key)
                to_bed(src, os.path.join(MUSIC, name))
        except KeyRejected as e:
            print(name, "FAILED:", e, "- the key itself was refused (GEMINI_API_KEY / GOOGLE_API_KEY, environment or .env);"
                  " not trying the other tracks", flush=True)
            break
        except Unavailable as e:
            print(name, "FAILED:", e, "- no Lyria model can serve this key now; not trying the other tracks", flush=True)
            break
        except Exception as e:
            print(name, "FAILED:", e, flush=True)
            continue
        made += 1
        _record({"file": name, "provider": "lyria", "model": model, "mode": "generate", "prompt": prompt,
                 "seconds": LENGTH, "licence": LICENCE["lyria"], "made": time.strftime("%Y-%m-%d")})
        print(name, f"ok (lyria {model}, {time.time() - t:.0f}s)", flush=True)
    print(f"{made}/{len(todo)} tracks in assets/music", flush=True)
    return made


def media_use_dir():
    for d in MEDIA_USE:
        if d and os.path.exists(os.path.join(d, "audio", "scripts", "audio.mjs")):
            return d
    raise SystemExit("media-use skill not found (install the HyperFrames plugin, or set HYPERFRAMES_MEDIA_USE)")


