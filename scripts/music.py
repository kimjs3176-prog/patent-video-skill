"""Prepare background music when assets/music is empty.

Usage:
  python -I tools/music.py --check                                   # which routes work on this PC (changes nothing)
  python -I tools/music.py --mode compose|retrieve|generate [--count 4] [--force] [--allow-install]

  compose    no key, no service: the pipeline composes and performs the beds itself (compose.py; numpy + ffmpeg,
             about 25 s a track). Original material with no third-party rights. The default when there is no key.

  generate   Google Lyria 3.5 straight through the Gemini API when GEMINI_API_KEY (or GOOGLE_API_KEY) is set in the
             environment or the project's .env: full-length 44.1 kHz stereo instrumentals, the best route. Without a key,
             local MusicGen through the HyperFrames media-use engine (first run pip-installs transformers + torch and
             downloads ~300 MB; slow on CPU; MusicGen weights are CC-BY-NC 4.0, non-commercial)
  retrieve   HeyGen music library through media-use, searched by mood (HeyGen sign-in or HEYGEN_API_KEY; uses credits)

produce.py calls ensure() before a batch: it makes whichever of the default beds m01..m04 assets/music lacks, with Lyria
when a Gemini key is set (a few cents per track; whatever Lyria does not deliver is composed), otherwise by composing
(free). A folder holding mp3s of the user's own is left alone. --no-music-gen skips that.

Writes assets/music/m<NN>-<mood>.mp3 (60.5 s, faded in and out, crossfade-looped when the source is shorter) and
assets/music/SOURCES.json (provider, mode, query/prompt, licence note). The builders rotate whatever mp3s are in
assets/music in production order, so a few tracks cover any number of videos. Without --force it only fills the missing
beds of the default set, and refuses when the set is complete or the folder holds the user's own mp3s; --force adds
count more after them. Pick the route with the user first (media-use preflight): never generate silently.
"""
